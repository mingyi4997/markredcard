/**
 * 转换小红书表情文本为emoji
 */
export function convertRedbookEmoji(text: string): string {
  let result = text

  // 使用正则表达式匹配所有 [表情] 格式
  const regex = /\[([^\]]+)\]/g

  result = result.replace(regex, (match, emojiName) => {
    const fullMatch = `[${emojiName}]`
    return REDBOOK_EMOJI_MAP[fullMatch] || match
  })

  return result
}

/**
 * 批量转换HTML中的表情文本
 */
export function convertEmojiInHTML(html: string): string {
  return convertRedbookEmoji(html)
}
